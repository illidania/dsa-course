#include <iostream>
#include <vector>
#include <algorithm> // Для std::swap

using namespace std;

/**
 * ==========================================
 * ALGORITHM: BUBBLE SORT (Сортировка пузырьком)
 * ==========================================
 * 
 * ИДЕЯ:
 * Представьте, что элементы массива — это пузырьки в воде. 
 * Более легкие всплывают наверх, более тяжелые (большие числа) тонут на дно.
 * Мы многократно проходим по массиву. На каждом проходе мы сравниваем 
 * два соседних элемента. Если левый больше правого, они стоят неправильно -> меняем их местами.
 * 
 * ПОЧЕМУ ЭТО РАБОТАЕТ:
 * После первого полного прохода самый большой элемент гарантированно "всплывет" 
 * в самый конец массива (на позицию N-1).
 * После второго прохода второй по величине элемент встанет на позицию N-2.
 * И так далее.
 * 
 * СЛОЖНОСТЬ:
 * Временная: O(N^2) - из-за двух вложенных циклов. Очень медленно на больших данных.
 * Пространственная: O(1) - сортировка происходит на месте (in-place).
 */

void bubble_sort(vector<int>& A) {
    int n = A.size();
    
    // Внешний цикл отвечает за количество проходов.
    // Нам нужно сделать N-1 проходов, чтобы гарантированно всё отсортировать.
    for (int i = 0; i < n - 1; i++) {
        
        bool swapped = false; // Оптимизация: флаг, были ли обмены
        
        // Внутренний цикл проходит по массиву и делает обмены.
        // Обратите внимание на условие: j < n - i - 1
        // "- i" нужно, потому что последние i элементов уже точно отсортированы 
        // на предыдущих итерациях, их трогать нет смысла.
        for (int j = 0; j < n - i - 1; j++) {
            
            // Сравнение соседей
            if (A[j] > A[j + 1]) {
                // Если левый больше правого -> меняем местами
                swap(A[j], A[j + 1]);
                swapped = true;
            }
        }
        
        // Если за полный проход не было ни одного обмена, 
        // значит массив УЖЕ отсортирован. Можно выходить досрочно.
        if (!swapped) {
            break;
        }
    }
}

int main() {
    vector<int> data = {64, 34, 25, 12, 22, 11, 90};
    bubble_sort(data);
    
    cout << "Sorted array: ";
    for (int x : data) cout << x << " ";
    cout << endl;
    return 0;
}
