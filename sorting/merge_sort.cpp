#include <iostream>
#include <vector>

using namespace std;

/**
 * ==========================================
 * ALGORITHM: MERGE SORT (Сортировка слиянием)
 * ==========================================
 * 
 * ИДЕЯ:
 * "Разделяй и властвуй". Сложно отсортировать огромный массив сразу.
 * Но очень легко слить два УЖЕ отсортированных маленьких массива в один большой.
 * 
 * Алгоритм:
 * 1. Разделить массив пополам.
 * 2. Рекурсивно вызвать сортировку для левой половины.
 * 3. Рекурсивно вызвать сортировку для правой половины.
 * 4. Слить (Merge) две полученные отсортированные половинки в одну.
 * 
 * Базовый случай рекурсии: массив из 1 элемента уже считается отсортированным.
 * 
 * СЛОЖНОСТЬ:
 * Временная: O(N log N) всегда (и в лучшем, и в худшем случае). Это очень круто.
 * Пространственная: O(N) - требуется дополнительная память для временных массивов при слиянии.
 */

// Функция слияния двух отсортированных подмассивов:
// Первый подмассив: A[left...mid]
// Второй подмассив: A[mid+1...right]
void merge(vector<int>& A, int left, int mid, int right) {
    int n1 = mid - left + 1; // Длина левой части
    int n2 = right - mid;    // Длина правой части

    // Создаем временные массивы (Extra memory O(N))
    vector<int> L(n1), R(n2);

    // Копируем данные
    for (int i = 0; i < n1; i++) L[i] = A[left + i];
    for (int j = 0; j < n2; j++) R[j] = A[mid + 1 + j];

    // Индексы для прохода по массивам
    int i = 0; // Индекс в L
    int j = 0; // Индекс в R
    int k = left; // Индекс в основном массиве A

    // Пока в обоих массивах есть элементы, выбираем меньший и кладем в A
    while (i < n1 && j < n2) {
        if (L[i] <= R[j]) {
            A[k] = L[i];
            i++;
        } else {
            A[k] = R[j];
            j++;
        }
        k++;
    }

    // Если в L остались элементы, дописываем их
    while (i < n1) {
        A[k] = L[i];
        i++;
        k++;
    }
    // Если в R остались элементы, дописываем их
    while (j < n2) {
        A[k] = R[j];
        j++;
        k++;
    }
}

// Рекурсивная функция сортировки
void merge_sort(vector<int>& A, int left, int right) {
    // Базовый случай: если left >= right, значит в подмассиве 0 или 1 элемент.
    // Сортировать нечего.
    if (left >= right) return;

    // Находим середину
    int mid = left + (right - left) / 2;

    // Шаг 1 и 2: Рекурсивно делим и сортируем
    merge_sort(A, left, mid);
    merge_sort(A, mid + 1, right);

    // Шаг 3: Сливаем результаты
    merge(A, left, mid, right);
}

int main() {
    vector<int> data = {38, 27, 43, 3, 9, 82, 10};
    merge_sort(data, 0, data.size() - 1);
    
    cout << "Sorted array: ";
    for (int x : data) cout << x << " ";
    cout << endl;
    return 0;
}
