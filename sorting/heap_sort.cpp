#include <iostream>
#include <vector>
#include <algorithm>

using namespace std;

/**
 * ==========================================
 * ALGORITHM: HEAP SORT (Пирамидальная сортировка)
 * ==========================================
 * 
 * ИДЕЯ:
 * Мы превращаем массив в специальную структуру — Двоичную Кучу (Binary Heap).
 * Свойство Max-Heap: Значение в любом узле больше или равно значений в его детях.
 * Следовательно, самый большой элемент ВСЕГДА находится в корне (индекс 0).
 * 
 * Алгоритм:
 * 1. Превратить беспорядочный массив в Max-Heap.
 * 2. Пока куча не пуста:
 *    - Взять корень (максимум) и поменять его с последним элементом массива.
 *    - Теперь максимум "заморожен" в конце массива и считается отсортированным.
 *    - Уменьшить размер кучи на 1.
 *    - Вызвать процедуру "чинки" кучи (heapify) для нового корня, чтобы вернуть свойство Max-Heap.
 * 
 * Арифметика индексов (для массива начинающегося с 0):
 * Левый ребенок: 2*i + 1
 * Правый ребенок: 2*i + 2
 * 
 * СЛОЖНОСТЬ:
 * Временная: O(N log N) гарантированно.
 * Пространственная: O(1) - in-place, не требует доп. памяти.
 */

// Функция Heapify (Просеивание вниз)
// Принимает: массив A, размер кучи n, индекс узла i
// Задача: "утопить" элемент A[i] вниз, если он меньше своих детей
void heapify(vector<int>& A, int n, int i) {
    int largest = i;       // Инициализируем, считая, что корень — самый большой
    int left = 2 * i + 1;  // Левый потомок
    int right = 2 * i + 2; // Правый потомок

    // Если левый ребенок существует и больше корня
    if (left < n && A[left] > A[largest])
        largest = left;

    // Если правый ребенок существует и больше самого большого найденного
    if (right < n && A[right] > A[largest])
        largest = right;

    // Если самый большой элемент — не корень
    if (largest != i) {
        swap(A[i], A[largest]); // Меняем местами корень и ребенка

        // Рекурсивно "чиним" поддерево, которое мы могли сломать
        heapify(A, n, largest);
    }
}

void heap_sort(vector<int>& A) {
    int n = A.size();

    // Шаг 1: Построение кучи (Build Heap)
    // Начинаем с последнего узла, у которого есть дети (n/2 - 1), и идем к корню.
    for (int i = n / 2 - 1; i >= 0; i--)
        heapify(A, n, i);

    // Шаг 2: Извлечение элементов
    for (int i = n - 1; i > 0; i--) {
        // Перемещаем текущий корень (макс. элемент) в конец
        swap(A[0], A[i]);

        // Вызываем heapify на уменьшенной куче (размер i),
        // чтобы найти новый максимум для корня
        heapify(A, i, 0);
    }
}

int main() {
    vector<int> data = {12, 11, 13, 5, 6, 7};
    heap_sort(data);
    
    cout << "Sorted array: ";
    for (int x : data) cout << x << " ";
    cout << endl;
    return 0;
}
