#include <iostream>
#include <vector>
#include <algorithm>

using namespace std;

/**
 * ==========================================
 * ALGORITHM: QUICK SORT (Быстрая сортировка)
 * ==========================================
 * 
 * ИДЕЯ:
 * Тоже "Разделяй и властвуй", но по-другому.
 * Мы выбираем один элемент и называем его "Опорным" (Pivot).
 * Наша задача — перекидать элементы так, чтобы:
 * - Все, что МЕНЬШЕ опорного, оказалось СЛЕВА от него.
 * - Все, что БОЛЬШЕ опорного, оказалось СПРАВА от него.
 * Сам опорный элемент встанет на свое финальное, правильное место.
 * После этого рекурсивно повторяем процесс для левой и правой части.
 * 
 * СЛОЖНОСТЬ:
 * В среднем: O(N log N).
 * В худшем (если массив уже отсортирован и мы неудачно берем pivot): O(N^2).
 * Пространство: O(log N) на стек вызовов рекурсии (In-Place версия).
 */

// Функция Partition (Разбиение)
// Выбирает последний элемент как pivot и расставляет элементы относительно него.
int partition(vector<int>& A, int low, int high) {
    int pivot = A[high]; // Опорный элемент
    
    // i будет указывать на границу "зоны маленьких чисел" (тех, что меньше pivot)
    // Изначально зона пуста, поэтому low - 1
    int i = (low - 1);

    // Проходим по всему подмассиву
    for (int j = low; j <= high - 1; j++) {
        // Если текущий элемент меньше или равен pivot
        if (A[j] <= pivot) {
            i++; // Расширяем зону маленьких чисел
            swap(A[i], A[j]); // Закидываем этот элемент в зону маленьких
        }
    }
    
    // В конце ставим сам pivot сразу ПОСЛЕ зоны маленьких чисел.
    // Теперь pivot стоит на своем законном месте.
    swap(A[i + 1], A[high]);
    
    return (i + 1); // Возвращаем индекс, где теперь стоит pivot
}

void quick_sort(vector<int>& A, int low, int high) {
    if (low < high) {
        // pi - индекс разделения. A[pi] уже стоит на своем месте.
        int pi = partition(A, low, high);

        // Рекурсивно сортируем левую часть (до pivot)
        quick_sort(A, low, pi - 1);
        // Рекурсивно сортируем правую часть (после pivot)
        quick_sort(A, pi + 1, high);
    }
}

int main() {
    vector<int> data = {10, 7, 8, 9, 1, 5};
    quick_sort(data, 0, data.size() - 1);
    
    cout << "Sorted array: ";
    for (int x : data) cout << x << " ";
    cout << endl;
    return 0;
}
