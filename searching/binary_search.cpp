#include <iostream>
#include <vector>

using namespace std;

/**
 * ==========================================
 * ALGORITHM: BINARY SEARCH (Бинарный поиск)
 * ==========================================
 * 
 * ТРЕБОВАНИЕ:
 * Массив ОБЯЗАТЕЛЬНО должен быть отсортирован.
 * 
 * ИДЕЯ:
 * Похоже на поиск слова в бумажном словаре. Мы не листаем по одной странице.
 * Мы открываем книгу посередине.
 * - Если искомое слово раньше середины -> отбрасываем правую половину книги.
 * - Если позже -> отбрасываем левую.
 * Повторяем процесс с оставшейся частью.
 * Каждый шаг сокращает область поиска в 2 раза.
 * 
 * СЛОЖНОСТЬ:
 * Временная: O(log N).
 * Для 1 миллиона элементов нужно всего ~20 сравнений! (2^20 approx 10^6)
 */

int binary_search(const vector<int>& A, int target) {
    int low = 0;
    int high = A.size() - 1;

    while (low <= high) {
        // Находим середину.
        // Формула left + (right - left) / 2 защищает от переполнения integer,
        // которое может случиться при (left + right) / 2, если числа очень большие.
        int mid = low + (high - low) / 2;

        if (A[mid] == target) {
            return mid; // Нашли! Возвращаем индекс
        }

        if (A[mid] < target) {
            // Если середина меньше цели, значит цель где-то справа
            low = mid + 1;
        } else {
            // Если середина больше цели, значит цель где-то слева
            high = mid - 1;
        }
    }

    return -1; // Элемент не найден
}

int main() {
    // Массив должен быть отсортирован!
    vector<int> data = {2, 5, 8, 12, 16, 23, 38, 56, 72, 91};
    int target = 23;
    
    int result = binary_search(data, target);
    
    if (result != -1)
        cout << "Element found at index: " << result << endl;
    else
        cout << "Element not found" << endl;
        
    return 0;
}
